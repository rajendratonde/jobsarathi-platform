"""Primary key generation.

v5 §29: every table's ``id`` is a UUIDv7 generated by the service, so keys
are time-ordered (B-tree inserts stay local) yet unguessable.
"""

from __future__ import annotations

import os
import threading
import time
import uuid

_lock = threading.Lock()
_last_ms = 0
_counter = 0


def uuid7() -> uuid.UUID:
    """Return a RFC 9562 version-7 UUID.

    48 bits of Unix milliseconds, then a 12-bit counter that keeps IDs made in
    the same millisecond in order, then 62 random bits.
    """
    global _last_ms, _counter
    with _lock:
        now_ms = time.time_ns() // 1_000_000
        if now_ms > _last_ms:
            _last_ms = now_ms
            _counter = int.from_bytes(os.urandom(2), "big") & 0x07FF  # leave room to count up
        else:
            _counter += 1
            if _counter > 0x0FFF:  # counter exhausted inside one millisecond: borrow the next one
                _last_ms += 1
                _counter = 0
            now_ms = _last_ms
        counter = _counter
    rand = int.from_bytes(os.urandom(8), "big") & ((1 << 62) - 1)
    value = (now_ms & ((1 << 48) - 1)) << 80
    value |= 0x7 << 76
    value |= counter << 64
    value |= 0b10 << 62
    value |= rand
    return uuid.UUID(int=value)
